import {test,expect} from '@playwright/test';
test('compare sample runs, inspect definitions, reverse direction and export evidence',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Try the demo',exact:true}).click();
 await page.getByRole('button',{name:'Test runs',exact:true}).click();
 await page.getByRole('button',{name:'Compare runs',exact:true}).click();
 const panel=page.getByRole('region',{name:'Run comparison'});
 await expect(panel.getByLabel('Baseline run')).toContainText('Sample baseline');
 await panel.getByLabel('Baseline run').selectOption({label:'Sample baseline · comparison'});
 await panel.getByLabel('Candidate run').selectOption({label:'Sample candidate · comparison'});
 await expect(panel.locator('.comparison-counts')).toContainText('New failures');
 await panel.getByLabel('Show changes').selectOption('regression');
 await expect(panel.locator('.comparison-row')).toHaveCount(1);
 await expect(panel.locator('.comparison-row')).toContainText('Customer can sign in');
 await panel.getByText('Saved definition and observation',{exact:true}).first().click();
 await expect(panel.getByText('Expected: The customer sees their account dashboard.',{exact:true}).first()).toBeVisible();
 const downloadEvent=page.waitForEvent('download');
 await panel.getByRole('button',{name:'Export comparison',exact:true}).click();
 const download=await downloadEvent;
 const stream=await download.createReadStream();
 let text='';for await (const chunk of stream!) text+=chunk;
 const report=JSON.parse(text);
 expect(report.summary.regression).toBe(1);expect(report.summary.fixed).toBe(1);
 expect(report.baseline.name).toBe('Sample baseline · comparison');
 await panel.getByRole('button',{name:'Swap baseline and candidate'}).click();
 await expect(panel.getByLabel('Baseline run')).toHaveValue(report.candidate.id);
 await expect(panel.locator('.comparison-row')).toHaveCount(1);
 await expect(panel.locator('.comparison-row')).toContainText('Invalid password');
 await panel.getByLabel('Candidate run').selectOption(report.candidate.id);
 await expect(panel.getByRole('alert')).toContainText('Choose two different runs');
 await expect(panel.getByRole('button',{name:'Export comparison'})).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});
 await panel.getByLabel('Candidate run').selectOption(report.baseline.id);
 await expect(panel.locator('.comparison-row')).toHaveCount(1);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'docs/comparison-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await panel.getByLabel('Show changes').selectOption('all');
 await expect(panel.locator('.comparison-row')).toHaveCount(7);
 await page.screenshot({path:'docs/comparison.png',fullPage:true});
});
