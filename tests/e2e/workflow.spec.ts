import { test, expect } from '@playwright/test';
test('create a case, execute it and create a linked defect',async({page})=>{
 await page.goto('/');
 const email=`browser-${Date.now()}@example.test`;
 await page.getByLabel('Your name',{exact:true}).fill('Browser tester');
 await page.getByLabel('Email',{exact:true}).fill(email);
 await page.getByLabel('Password',{exact:true}).fill('Synthetic-password-123!');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await page.getByRole('button',{name:'Create project',exact:true}).first().click();
 const projectName=`Browser project ${Date.now()}`;
 await page.getByLabel('Project name').fill(projectName);
 await page.getByRole('button',{name:'Create project',exact:true}).last().click();
 await page.getByRole('button',{name:'New test case',exact:true}).first().click();
 await page.getByLabel('Title',{exact:true}).fill('Customer receives confirmation');
 await page.getByLabel('Step 1',{exact:true}).fill('Submit checkout');
 await page.getByLabel('Expected result',{exact:true}).fill('Confirmation appears');
 await page.getByRole('button',{name:'Create test case',exact:true}).click();
 await page.getByRole('button',{name:'Test runs',exact:true}).click();
 await page.getByRole('button',{name:'Create test run',exact:true}).click();
 await page.getByLabel('Run name').fill('Browser regression');
 await page.getByRole('dialog').getByRole('button',{name:'Create test run',exact:true}).click();
 await page.getByRole('button',{name:/Customer receives confirmation/}).click();
 await page.getByRole('combobox',{name:'Result',exact:true}).selectOption('failed');
 await page.getByLabel('Observation').fill('Confirmation does not appear');
 await page.getByRole('button',{name:'Save result'}).click();
 await page.getByRole('button',{name:'Create defect',exact:true}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Create defect',exact:true}).click();
 await page.getByRole('button',{name:'View defect'}).click();
 await expect(page.getByRole('dialog')).toContainText('Confirmation does not appear');
 await page.reload();
 await page.getByRole('combobox',{name:'Current project'}).selectOption({label:projectName});
 await page.getByRole('button',{name:/Defects/}).first().click();
 await expect(page.getByRole('button',{name:/Customer receives confirmation/})).toBeVisible();
});
